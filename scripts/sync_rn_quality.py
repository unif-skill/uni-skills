#!/usr/bin/env python3
"""从 RN 开发技能同步默认检查资料；各分发技能保留独立可用的副本。"""

import argparse
from pathlib import Path


OWNER = 'uni-rn-dev'
CONSUMERS = ('uni-rn-library', 'uni-github-delivery-setup')


def safe_path(root: Path, relative: Path) -> Path:
    path = root
    for part in relative.parts:
        path = path / part
        if path.is_symlink():
            raise ValueError(f'拒绝通过符号链接同步：{relative}')
    return path


def sync_quality(root: str | Path, check: bool = False) -> int:
    root = Path(root).resolve()
    owner = Path('skills') / OWNER
    source = root / owner
    document = Path('references/quality.md')
    templates = Path('templates/quality')
    if not (source / document).is_file() or not (source / templates).is_dir():
        raise ValueError('缺少 RN 默认检查规范或模板来源')
    files = [document, *sorted(path.relative_to(source) for path in (source / templates).rglob('*') if path.is_file())]
    expected = {relative: safe_path(root, owner / relative).read_bytes() for relative in files}
    writes: list[tuple[Path, bytes]] = []
    differences: list[str] = []
    for name in CONSUMERS:
        for relative, content in expected.items():
            target = Path('skills') / name / relative
            path = safe_path(root, target)
            if relative == document:
                content = b'<!-- Generated by scripts/sync_rn_quality.py from uni-rn-dev. -->\n\n' + content
            if not path.is_file() or path.read_bytes() != content:
                differences.append(str(target))
                writes.append((path, content))
    if check and differences:
        raise ValueError('RN 默认检查副本不一致：\n' + '\n'.join(differences))
    if not check:
        for path, content in writes:
            path.parent.mkdir(parents=True, exist_ok=True)
            _ = path.write_bytes(content)
    return len(expected) * len(CONSUMERS)


class Arguments(argparse.Namespace):
    root: Path = Path(__file__).resolve().parents[1]
    check: bool = False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument('--root', type=Path, default=Arguments.root)
    _ = parser.add_argument('--check', action='store_true')
    args = parser.parse_args(namespace=Arguments())
    try:
        count = sync_quality(args.root, check=args.check)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{error}\n')
    print(f'RN 默认检查资料：{count} 个分发副本已核对。')


if __name__ == '__main__':
    main()
